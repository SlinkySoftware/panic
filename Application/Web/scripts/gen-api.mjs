#!/usr/bin/env node
// Generates src/api/generated/openapi.ts from Documents/Architecture/openapi/server.yaml (AR-1.7).
//
//   npm run gen:api            write the file
//   npm run gen:api -- --check exit 1 if the committed file is stale (also enforced by test/unit/apiGenerated.spec.ts)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SPEC_FILE = resolve(here, '../../../Documents/Architecture/openapi/server.yaml');
export const OUT_FILE = resolve(here, '../src/api/generated/openapi.ts');

const HEADER = `/* eslint-disable */
// GENERATED by \`npm run gen:api\` (openapi-typescript) from Documents/Architecture/openapi/server.yaml.
// DO NOT EDIT. A unit test fails when this file is stale relative to the spec.

`;

/** @returns {Promise<string>} the TypeScript source for the current spec */
export async function generate() {
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(pathToFileURL(SPEC_FILE), { alphabetize: false });
  return HEADER + astToString(ast);
}

async function main() {
  const src = await generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT_FILE, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== src) {
      console.error('src/api/generated/openapi.ts is stale: run `npm run gen:api` and commit the result.');
      process.exit(1);
    }
    console.info('src/api/generated/openapi.ts is up to date.');
    return;
  }
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, src);
  console.info(`wrote ${OUT_FILE}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
