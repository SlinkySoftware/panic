"""Generate panic-web's nginx server template from ``Application/Web/proxy-paths.json`` (AR-6.4).

The JSON allow-list is the only source of truth for which server paths panic-web proxies; the dev proxy
(``dev-proxy.ts``) reads the same file. The output is an nginx *template*: the official image runs envsubst
on it at start, filtered to ``PANIC_SERVER_URL`` and ``PANIC_BASE_PATH`` (``NGINX_ENVSUBST_FILTER``), so
every other ``$`` stays an nginx variable.

``PANIC_BASE_PATH`` is the URL prefix (``''`` or e.g. ``/panic``, normalised by the image's entrypoint):
every location sits below it, the full path (prefix included) goes to panic-server, and index.html's
``<base href="/">`` is rewritten to ``<base href="/panic/">`` so the SPA (built with relative asset URLs)
knows where it lives. Outside the prefix only ``/healthz`` answers.

    gen_nginx_conf.py [--paths proxy-paths.json] [--out default.conf.template]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PATHS = ROOT / "Application/Web/proxy-paths.json"
_SAFE_PATH = re.compile(r"^/[A-Za-z0-9/_.\-]*$")
NEVER_PROXIED = ("/metrics",)
#: The URL prefix, filled in by envsubst at container start.
BASE = "${PANIC_BASE_PATH}"
HTML = "/usr/share/nginx/html"

# Strict CSP for the SPA: everything same-origin; Quasar injects inline styles at runtime.
CSP = (
    "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; "
    "font-src 'self' data:; connect-src 'self'; object-src 'none'; base-uri 'self'; "
    "frame-ancestors 'none'; form-action 'self'"
)

SECURITY_HEADERS = f"""\
    add_header X-Content-Type-Options "nosniff" always;
    add_header X-Frame-Options "DENY" always;
    add_header Referrer-Policy "same-origin" always;
    add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;
    add_header Content-Security-Policy "{CSP}" always;"""

PROXY_BLOCK = """\
        proxy_pass ${PANIC_SERVER_URL};
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $panic_forwarded_proto;
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header Connection "";
        proxy_read_timeout 60s;
        proxy_buffering on;"""


def load_paths(path: Path) -> tuple[list[str], list[str]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    prefixes, exact = list(data["prefixes"]), list(data["exact"])
    for p in prefixes + exact:
        if not _SAFE_PATH.match(p):
            raise ValueError(f"unsafe path in allow-list: {p!r}")
        if any(p == n or p.startswith(n + "/") or (p.endswith("/") and n.startswith(p)) for n in NEVER_PROXIED):
            raise ValueError(f"{p!r} must never be proxied (AR-6.4)")
    for p in prefixes:
        if not p.endswith("/"):
            raise ValueError(f"prefix must end with '/': {p!r}")
    return prefixes, exact


def render(prefixes: list[str], exact: list[str]) -> str:
    locations = [f"    location ^~ {BASE}{p} {{\n{PROXY_BLOCK}\n    }}" for p in prefixes]
    locations += [f"    location = {BASE}{p} {{\n{PROXY_BLOCK}\n    }}" for p in exact]
    blocked = "\n".join(f"    location = {BASE}{p} {{ return 404; }}" for p in NEVER_PROXIED)
    headers = SECURITY_HEADERS.replace("    add_header", "        add_header")
    return f"""\
# GENERATED by Build/scripts/gen_nginx_conf.py from Application/Web/proxy-paths.json. Do not edit.
# envsubst replaces only ${{PANIC_SERVER_URL}} and ${{PANIC_BASE_PATH}} at container start (NGINX_ENVSUBST_FILTER).

# Keep an upstream TLS terminator's scheme when it sent one; otherwise this hop's.
map $http_x_forwarded_proto $panic_forwarded_proto {{
    default $http_x_forwarded_proto;
    ""      $scheme;
}}

server {{
    listen 8080;
    listen [::]:8080;
    server_name _;
    server_tokens off;
    # Redirects stay relative: behind another proxy this container's host and port are not the browser's.
    absolute_redirect off;
    client_max_body_size 2m;

    gzip on;
    gzip_vary on;
    gzip_min_length 1024;
    gzip_types text/css application/javascript application/json image/svg+xml text/plain;

{SECURITY_HEADERS}

    location = /healthz {{
        access_log off;
        default_type text/plain;
        return 200 "ok\\n";
    }}

{blocked}

    # Allow-listed server paths (AR-6.4): nothing else reaches panic-server.
{chr(10).join(locations)}

    # Any other API path is not proxied.
    location ^~ {BASE}/api/ {{ return 404; }}
    location ^~ {BASE}/auth/ {{ return 404; }}

    # Fingerprinted build output: cache forever.
    location ^~ {BASE}/assets/ {{
{headers}
        add_header Cache-Control "public, max-age=31536000, immutable" always;
        alias {HTML}/assets/;
    }}

    # SPA: a file of the build, else a client-side route.
    location ^~ {BASE}/ {{
{headers}
        add_header Cache-Control "no-cache" always;
        root {HTML};
        rewrite ^{BASE}(/.*)$ $1 break;
        try_files $uri @index;
        sub_filter '<base href="/">' '<base href="{BASE}/">';
    }}

    location @index {{
{headers}
        add_header Cache-Control "no-cache" always;
        root {HTML};
        try_files /index.html =404;
        sub_filter '<base href="/">' '<base href="{BASE}/">';
    }}

    # Under a prefix: the bare prefix gets its slash, and nothing outside it is PANIC's. (Without a prefix the
    # first never matches, and `location ^~ /` above takes every request before the second is consulted.)
    location ~ ^{BASE}$ {{ return 301 {BASE}/; }}
    location ~ ^/ {{ return 404; }}
}}
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--paths", type=Path, default=DEFAULT_PATHS)
    ap.add_argument("--out", type=Path, default=None, help="write here (default: stdout)")
    args = ap.parse_args(argv)
    text = render(*load_paths(args.paths))
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
